// lib/duosynergy.mjs — static per-patch bot-lane (ADC+SUPPORT) duo synergy snapshot, same
// philosophy as lib/counters.mjs and lib/champstats.mjs: a curated, community-editable data file
// rather than a live API call.
//
// Source: https://op.gg/lol/champions/{champ}/synergies/adc — each ADC's own page (support-role
// section) lists their top-10 support partners by play count, with pair winrate + games. Fetched
// 2026-08-17 for the 27 champions that are actually played bot-lane ADC in practice (Data
// Dragon's "Marksman" tag also includes off-role picks like Azir/Jayce/Kayle/Quinn/Teemo/
// TwistedFate that go mid/top, deliberately excluded here). One page fetch per ADC — this data
// isn't in a single aggregate table the way champstats.mjs's champion-stats page was, since
// synergy is inherently pairwise.
// Patch: 16.16.1 (same source as champstats.mjs, read from the embedded data's own image URLs).
//
// Keyed "Adc+Supp" using match-v5's internal championName for both halves (cross-joined against
// Data Dragon's champion.json exactly like champstats.mjs — including the same Jade_-prefix
// pseudo-champion filter: Data Dragon lists 60 alternate-universe duplicate entries sharing a
// real champion's display name, e.g. both "Ezreal" and "Jade_Ezreal" have name="Ezreal"; excluded
// by their tell, numeric key >= 10000, before building the name-lookup).
//
// Coverage is inherently a top-10-per-ADC list, not exhaustive — 270 pairs across 27 ADCs. A real
// pairing missing here (confirmed while building the acceptance case for this feature: neither
// Draven+Yuumi nor Xayah+Galio appear, both being off-meta enough to fall outside either ADC's
// top-10) just means no synergy chip/tag renders and no scoring adjustment applies for that lane —
// same "missing data -> no display, never a fabricated number" rule as champstats.mjs.
//
// `games` is included specifically so a low-sample pair (the rarer ADCs — Akshan, Corki, Graves,
// Kindred — have entries as low as 11-20 games, real numbers, not filtered out) isn't presented
// with false confidence: it's shown directly in the tooltip alongside the winrate.
//
// synergyDelta (pair wr minus the mean of both champs' solo wr, from lib/champstats.mjs) is
// deliberately NOT stored here — it's computed at the point of use (lib/riot.mjs and its
// src/main.js mirror) so it always reflects whatever champstats.mjs's solo-wr numbers currently
// are, rather than baking in a delta that could silently drift out of sync with a champstats.mjs
// update.
//
// Refresh cadence: once per patch, alongside champstats.mjs. PRs welcome to bump PATCH and re-run
// the same per-ADC op.gg fetch + Data Dragon cross-check.
